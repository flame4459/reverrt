#!/usr/bin/env python3
"""Install generated sprites into the app and emit the model -> asset map.

Takes the renders in ``pilot/generated``, applies the house keyline so every
sprite shares an outline weight, writes one ``.imageset`` per sprite into
``BikeSprites.xcassets``, and generates ``BikeSpriteMap.swift`` so the app can
resolve a catalog model to its artwork.

The existing hand-finished sprites are never touched: their assets keep their
current names and the generated map only fills gaps.

Usage:
    python3 Scripts/install_sprites.py --dry-run
    python3 Scripts/install_sprites.py
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT / "catalog" / "sprite-prompts.csv"
SOURCE = ROOT / "pilot" / "generated"
ASSETS = ROOT / "revert" / "BikeSprites.xcassets"
SWIFT = ROOT / "revert" / "BikeSpriteMap.swift"
INK = (10, 10, 14)
PAD = 3


def keyline(image: Image.Image, color=INK) -> Image.Image:
    a = np.asarray(image.convert("RGBA"))
    mask = a[..., 3] > 40
    grow = mask.copy()
    grow[1:] |= mask[:-1]
    grow[:-1] |= mask[1:]
    grow[:, 1:] |= mask[:, :-1]
    grow[:, :-1] |= mask[:, 1:]
    out = a.copy()
    out[grow & ~mask] = [*color, 255]
    return Image.fromarray(out, "RGBA")


def pad(image: Image.Image, amount: int = PAD) -> Image.Image:
    out = Image.new("RGBA", (image.width + amount * 2, image.height + amount * 2), (0, 0, 0, 0))
    out.alpha_composite(image, (amount, amount))
    return out


def write_imageset(image: Image.Image, name: str) -> Path:
    imageset = ASSETS / f"{name}.imageset"
    imageset.mkdir(parents=True, exist_ok=True)
    png = imageset / f"{name}.png"
    image.save(png, format="PNG", optimize=True)
    contents = {
        "images": [
            {"filename": png.name, "idiom": "universal", "scale": "1x"},
            {"idiom": "universal", "scale": "2x"},
            {"idiom": "universal", "scale": "3x"},
        ],
        "info": {"author": "xcode", "version": 1},
        "properties": {"template-rendering-intent": "original"},
    }
    (imageset / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")
    return png


def swift_string(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    rows = list(csv.DictReader(PACK.open()))
    entries, written, skipped = {}, 0, 0

    for row in rows:
        asset = row["asset"]
        source = SOURCE / f"{asset}.png"
        if not source.exists():
            skipped += 1
            continue
        model = " ".join(part for part in (row["brand"], row["model"], row["years"]) if part).strip()
        model = " ".join(model.split())
        entries[model] = asset
        if args.dry_run:
            continue
        with Image.open(source) as im:
            write_imageset(pad(keyline(im.convert("RGBA"))), asset)
        written += 1

    if not args.dry_run:
        lines = [
            "// Generated by Scripts/install_sprites.py — do not edit by hand.",
            "// Catalog model name -> asset name in BikeSprites.xcassets.",
            "enum BikeSpriteMap {",
            "    static let entries: [String: String] = [",
        ]
        for model in sorted(entries):
            lines.append(f'        "{swift_string(model)}": "{entries[model]}",')
        lines += ["    ]", "}", ""]
        SWIFT.write_text("\n".join(lines))

    print(f"sprites installed: {written}   skipped (no render): {skipped}")
    print(f"map entries: {len(entries)} -> {SWIFT.relative_to(ROOT)}")
    if not args.dry_run:
        print(f"imagesets now: {len(list(ASSETS.glob('*.imageset')))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
