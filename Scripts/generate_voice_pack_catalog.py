#!/usr/bin/env python3
"""Generate the Revert voice-pack catalogue from the community archive.

The archive in ``waze-voicepack-links-main/helper_files/waze_vps.json`` lists
every Waze voice pack the community has preserved: official celebrity packs and
community recordings, each with the voice UUID that Waze serves the clips from.

``voice_pack_availability.json`` records whether Waze's CDN still answers for
each UUID.  In October 2026 Waze retired a large share of these links, so the
app hides the dead ones behind an "archived" filter instead of offering a
download that is guaranteed to fail.

Usage:
    python3 Scripts/generate_voice_pack_catalog.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ARCHIVE = ROOT / "waze-voicepack-links-main" / "helper_files" / "waze_vps.json"
AVAILABILITY = ROOT / "Scripts" / "voice_pack_availability.json"
OUTPUT = ROOT / "revert" / "VoicePackCatalogData.swift"


def swift_string(value: str) -> str:
    """Quote a Python string as a Swift string literal."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
        .replace("\t", " ")
    )
    return f'"{escaped}"'


def main() -> None:
    catalogue = json.loads(ARCHIVE.read_text())
    availability = json.loads(AVAILABILITY.read_text())
    reachable: dict[str, bool] = availability.get("results", {})

    entries = []
    seen: set[str] = set()
    for group, source in (("Official Voicepacks", "official"),
                          ("Community Voicepacks", "community")):
        for pack in catalogue.get(group, []):
            uuid = pack["uuid"].strip()
            if not uuid or uuid in seen:
                continue
            seen.add(uuid)
            entries.append(
                {
                    "id": uuid,
                    "name": pack["name"].strip(),
                    "language": pack.get("language", "Other").strip() or "Other",
                    "author": (pack.get("author") or "").strip() or None,
                    "source": source,
                    "downloadable": bool(reachable.get(uuid, False)),
                }
            )

    entries.sort(key=lambda item: (item["name"].lower(), item["language"].lower()))

    lines = [
        "// Generated by Scripts/generate_voice_pack_catalog.py — do not edit.",
        "// Source: waze-voicepack-links-main (community archive of Waze voices).",
        "",
        "extension VoicePack {",
        "    /// Every voice in the community archive, plus whether Waze's CDN",
        "    /// answered for it on the last availability check.",
        "    static let catalog: [VoicePack] = [",
    ]
    for entry in entries:
        author = swift_string(entry["author"]) if entry["author"] else "nil"
        lines.append(
            "        VoicePack(id: {id}, name: {name}, language: {language}, "
            "author: {author}, source: .{source}, downloadable: {downloadable}),".format(
                id=swift_string(entry["id"]),
                name=swift_string(entry["name"]),
                language=swift_string(entry["language"]),
                author=author,
                source=entry["source"],
                downloadable=str(entry["downloadable"]).lower(),
            )
        )
    lines += [
        "    ]",
        "",
        f"    /// When the catalogue's reachability flags were last refreshed.",
        f"    static let catalogCheckedAt = {swift_string(availability.get('checked_at', '')[:10])}",
        "}",
        "",
    ]

    OUTPUT.write_text("\n".join(lines))
    live = sum(1 for entry in entries if entry["downloadable"])
    print(f"Wrote {len(entries)} packs ({live} reachable) to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
