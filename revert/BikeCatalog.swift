import SwiftUI
import UIKit

/// How the picker groups bikes. Mirrors the categories in the prompt workbook.
enum BikeCategory: String, CaseIterable, Identifiable, Sendable {
    case sportbike = "Sportbike"
    case naked = "Naked"
    case cruiser = "Cruiser"
    case adventure = "Adventure"
    case touring = "Touring"
    case standard = "Standard"
    case dualSport = "Dual-sport"
    case scooter = "Scooter"
    case mini = "Mini"
    case supermoto = "Supermoto"
    case trike = "Trike"

    var id: String { rawValue }

    var title: String { rawValue }
}

struct BikeModel: Identifiable, Hashable, Sendable {
    let manufacturer: String
    let model: String
    let years: String
    let category: BikeCategory

    /// "Honda CBR929RR Fireblade 2000"
    var name: String {
        [manufacturer, model, years].filter { !$0.isEmpty }.joined(separator: " ")
    }

    /// "CBR929RR Fireblade" — the model without the year range.
    var designation: String {
        [model, years].filter { !$0.isEmpty }.joined(separator: " ")
    }

    var id: String { name }

    init?(line: String) {
        let parts = line.split(separator: "|", omittingEmptySubsequences: false).map(String.init)
        guard parts.count == 4, let category = BikeCategory(rawValue: parts[3]) else {
            assertionFailure("Malformed bike catalog line: \(line)")
            return nil
        }
        manufacturer = parts[0]
        model = parts[1]
        years = parts[2]
        self.category = category
    }
}

enum BikeCatalog {
    static let defaultBike = "Honda CBR125R 2004"

    /// Every selectable bike. Generated by `Scripts/generate_bike_catalog.py`
    /// from the sprite prompt workbook plus the hand-curated legacy entries.
    static let all: [BikeModel] = BikeCatalogData.entries
        .split(separator: "\n", omittingEmptySubsequences: true)
        .compactMap { BikeModel(line: String($0)) }

    static let byName: [String: BikeModel] = Dictionary(
        uniqueKeysWithValues: all.map { ($0.name, $0) }
    )

    static func entry(named name: String) -> BikeModel? {
        byName[name]
    }

    static let grouped: [(String, [BikeModel])] = {
        let groups = Dictionary(grouping: all) { $0.manufacturer }
        return groups.keys.sorted { $0.localizedStandardCompare($1) == .orderedAscending }
            .map { ($0, groups[$0] ?? []) }
    }()

    static let countByCategory: [BikeCategory: Int] = {
        Dictionary(grouping: all, by: \.category).mapValues(\.count)
    }()
}


struct BikePickerView: View {
    @Environment(\.dismiss) private var dismiss
    @Binding var selectedBike: String
    @State private var query = ""
    @State private var category: BikeCategory?

    private var filteredGroups: [(String, [BikeModel])] {
        BikeCatalog.grouped.compactMap { manufacturer, bikes in
            let filtered = bikes.filter { bike in
                let matchesCategory = category == nil || bike.category == category
                let matchesQuery = query.isEmpty
                    || bike.name.localizedCaseInsensitiveContains(query)
                    || bike.category.rawValue.localizedCaseInsensitiveContains(query)
                return matchesCategory && matchesQuery
            }
            return filtered.isEmpty ? nil : (manufacturer, filtered)
        }
    }

    private var resultCount: Int {
        filteredGroups.reduce(0) { $0 + $1.1.count }
    }

    var body: some View {
        List {
            Section {
                VStack(spacing: 12) {
                    BikeShowcase(bikeName: selectedBike)

                    HStack(spacing: 8) {
                        Image(systemName: "magnifyingglass")
                            .font(.system(size: 15, weight: .semibold))
                            .foregroundStyle(MapUI.textTertiary)

                        TextField("Search bikes", text: $query)
                            .textInputAutocapitalization(.never)
                            .autocorrectionDisabled()
                            .foregroundStyle(MapUI.ink)

                        if !query.isEmpty {
                            Button {
                                query = ""
                            } label: {
                                Image(systemName: "xmark.circle.fill")
                                    .foregroundStyle(MapUI.textTertiary)
                            }
                            .accessibilityLabel("Clear bike search")
                        }
                    }
                    .padding(.horizontal, 12)
                    .frame(height: 44)
                    .background(MapUI.surfaceHigh, in: RoundedRectangle(cornerRadius: 14, style: .continuous))
                    .overlay {
                        RoundedRectangle(cornerRadius: 14, style: .continuous)
                            .strokeBorder(MapUI.line, lineWidth: 0.8)
                    }

                    categoryChips
                }
                .padding(.vertical, 6)
            }
            .listRowBackground(Color.clear)
            .listRowSeparator(.hidden)

            Section {
                Text(resultCount == 1 ? "1 bike" : "\(resultCount) bikes")
                    .font(.footnote)
                    .foregroundStyle(MapUI.textTertiary)
            }
            .listRowBackground(Color.clear)
            .listRowSeparator(.hidden)

            ForEach(filteredGroups, id: \.0) { manufacturer, bikes in
                Section(manufacturer) {
                    ForEach(bikes) { bike in
                        row(for: bike)
                    }
                }
            }
        }
        .listStyle(.plain)
        .navigationTitle("Choose your bike")
        .navigationBarTitleDisplayMode(.inline)
        .toolbar {
            ToolbarItem(placement: .topBarTrailing) {
                Button {
                    dismiss()
                } label: {
                    Image(systemName: "xmark")
                }
                .accessibilityLabel("Close bike picker")
            }
        }
        .tint(MapUI.accent)
    }

    private var categoryChips: some View {
        ScrollView(.horizontal, showsIndicators: false) {
            HStack(spacing: 8) {
                chip("All", isOn: category == nil) {
                    category = nil
                }

                ForEach(BikeCategory.allCases) { option in
                    chip(option.title, isOn: category == option) {
                        category = category == option ? nil : option
                    }
                }
            }
            .padding(.horizontal, 1)
            .padding(.vertical, 2)
        }
        .scrollClipDisabled()
    }

    private func chip(_ title: String, isOn: Bool, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            Text(title)
                .font(.system(.caption, design: .rounded).weight(.semibold))
                .foregroundStyle(isOn ? MapUI.accent : MapUI.textSecondary)
                .padding(.horizontal, 12)
                .padding(.vertical, 7)
                .background(
                    isOn ? MapUI.accent.opacity(0.16) : MapUI.surfaceHigh,
                    in: Capsule(style: .continuous)
                )
                .overlay {
                    Capsule(style: .continuous)
                        .strokeBorder(
                            isOn ? MapUI.accent.opacity(0.55) : MapUI.line,
                            lineWidth: 0.8
                        )
                }
        }
        .buttonStyle(.plain)
        .accessibilityAddTraits(isOn ? .isSelected : [])
    }

    private func row(for bike: BikeModel) -> some View {
        let isSelected = selectedBike == bike.name

        return Button {
            guard !isSelected else { return }
            withAnimation(RevertMotion.snappy) {
                selectedBike = bike.name
            }
            RevertHaptics.select()
        } label: {
            HStack(spacing: 12) {
                BikeArtworkView(bikeName: bike.name, width: 58, height: 36)

                VStack(alignment: .leading, spacing: 2) {
                    Text(bike.name)
                        .font(.system(.subheadline, design: .rounded).weight(isSelected ? .semibold : .regular))
                        .foregroundStyle(MapUI.ink)
                        .lineLimit(2)
                        .multilineTextAlignment(.leading)

                    Text(bike.category.title)
                        .font(.system(.caption2, design: .rounded).weight(.medium))
                        .foregroundStyle(MapUI.textTertiary)
                }

                Spacer(minLength: 6)

                if isSelected {
                    Image(systemName: "checkmark.circle.fill")
                        .font(.system(size: 18, weight: .semibold))
                        .foregroundStyle(MapUI.accent)
                        .transition(.scale.combined(with: .opacity))
                }
            }
            .padding(.vertical, 3)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .listRowBackground(
            isSelected ? MapUI.accent.opacity(0.09) : Color.clear
        )
        .accessibilityAddTraits(isSelected ? .isSelected : [])
    }
}
